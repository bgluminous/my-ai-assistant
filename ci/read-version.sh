#!/bin/sh
# Read the authoritative version and check its manually maintained companions.
set -eu
root=$(CDPATH= cd -P "$(dirname "$0")/.." && pwd)
cd "$root"
json=scripts/version-publish/json-tool.sh
version=$(sh "$json" get src-tauri/tauri.conf.json version)
canonical=$(sh "$json" version "$version")
[ "$version" = "$canonical" ] || { printf '%s\n' E_VERSION_CANONICAL >&2; exit 2; }
check() {
    [ "$1" = "$version" ] || { printf 'E_VERSION_MISMATCH_%s\n' "$2" >&2; exit 2; }
}
check "$(sh "$json" get package.json version)" package
check "$(sh "$json" get package-lock.json version)" lock
check "$(sh "$json" get package-lock.json packages..version)" lock_package
cargo=$(awk '
    /^\[package\][[:space:]]*$/ { package = 1; next }
    /^\[/ { package = 0 }
    package && /^[[:space:]]*version[[:space:]]*=/ {
        value = $0
        if (value !~ /^[[:space:]]*version[[:space:]]*=[[:space:]]*"[0-9]+\.[0-9]+\.[0-9]+"[[:space:]]*(#.*)?$/) exit 2
        sub(/^[^"]*"/, "", value); sub(/".*$/, "", value)
        found++; result = value
    }
    END { if (found != 1) exit 2; print result }
' src-tauri/Cargo.toml)
check "$cargo" cargo
# Cargo.lock is generated by Cargo; do not modify it or compile to refresh it here.
printf '%s\n' "$version"
